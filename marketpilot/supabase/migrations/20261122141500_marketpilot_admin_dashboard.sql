create table if not exists public.marketpilot_admins (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users (id) on delete cascade,
  email text check (email is null or email = lower(btrim(email))),
  check (user_id is not null or email is not null)
);

create unique index if not exists marketpilot_admins_user_id_unique
  on public.marketpilot_admins (user_id)
  where user_id is not null;

create unique index if not exists marketpilot_admins_email_unique
  on public.marketpilot_admins (email)
  where email is not null;

alter table public.marketpilot_admins enable row level security;
revoke all on public.marketpilot_admins from public, anon, authenticated;

create or replace function public.marketpilot_is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select auth.uid() is not null
    and exists (
      select 1
      from public.marketpilot_admins as admin
      where admin.user_id = auth.uid()
        or admin.email = lower(btrim(coalesce(auth.jwt() ->> 'email', '')))
    );
$$;

revoke all on function public.marketpilot_is_admin() from public, anon, authenticated;
grant execute on function public.marketpilot_is_admin() to authenticated;

create or replace function public.marketpilot_admin_dashboard_stats()
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  today_start_epoch bigint := pg_catalog.date_part(
    'epoch',
    pg_catalog.date_trunc('day', pg_catalog.now() at time zone 'UTC') at time zone 'UTC'
  )::bigint;
begin
  if not public.marketpilot_is_admin() then
    raise exception 'Administrator access is required' using errcode = '42501';
  end if;

  return pg_catalog.jsonb_build_object(
    'totalUsers',
      (select pg_catalog.count(*) from auth.users),
    'activeUsers',
      (
        select pg_catalog.count(*)
        from auth.users
        where last_sign_in_at >= pg_catalog.now() - interval '30 days'
      ),
    'dormantUsers',
      (
        select pg_catalog.count(*)
        from auth.users
        where last_sign_in_at is null
          or last_sign_in_at < pg_catalog.now() - interval '30 days'
      ),
    'depositsToday', null,
    'realLossesToday',
      coalesce((
        select pg_catalog.sum(-trade.profit)
        from public.marketpilot_practice_trades as trade
        where trade.account_type = 'real'
          and trade.status = 'lost'
          and trade.profit is not null
          and trade.exit_epoch >= today_start_epoch
      ), 0),
    'totalRealBalance',
      coalesce((
        select pg_catalog.sum(wallet.balance)
        from public.marketpilot_wallets as wallet
        where wallet.account_type = 'real'
      ), 0),
    'realWinRate',
      (
        select pg_catalog.round(
          100.0 * pg_catalog.count(*) filter (where trade.status = 'won')
          / nullif(pg_catalog.count(*), 0),
          1
        )
        from public.marketpilot_practice_trades as trade
        where trade.account_type = 'real'
          and trade.status in ('won', 'lost')
      ),
    'users',
      coalesce((
        select pg_catalog.jsonb_agg(
          pg_catalog.jsonb_build_object(
            'username', coalesce(profile.display_name, 'Unknown'),
            'email', coalesce(user_account.email, ''),
            'phone', profile.phone_e164,
            'activityStatus',
              case
                when user_account.last_sign_in_at >= pg_catalog.now() - interval '30 days'
                  then 'Active'
                else 'Dormant'
              end,
            'realBalance', coalesce(wallet.balance, 0)
          )
          order by user_account.created_at desc
        )
        from auth.users as user_account
        left join public.marketpilot_profiles as profile
          on profile.id = user_account.id
        left join public.marketpilot_wallets as wallet
          on wallet.user_id = user_account.id
          and wallet.account_type = 'real'
      ), '[]'::jsonb)
  );
end;
$$;

revoke all on function public.marketpilot_admin_dashboard_stats() from public, anon, authenticated;
grant execute on function public.marketpilot_admin_dashboard_stats() to authenticated;
